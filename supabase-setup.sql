-- NeonPlay shared online leaderboard (run in Supabase SQL Editor)
create table if not exists public.scores (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  player_name text not null check (char_length(player_name) between 1 and 24),
  game text not null check (char_length(game) between 1 and 60),
  score integer not null check (score >= 0),
  created_at timestamptz not null default now()
);

alter table public.scores enable row level security;

drop policy if exists "Anyone can read leaderboard scores" on public.scores;
create policy "Anyone can read leaderboard scores"
  on public.scores for select
  to anon, authenticated
  using (true);

drop policy if exists "Signed-in users can submit their own scores" on public.scores;
create policy "Signed-in users can submit their own scores"
  on public.scores for insert
  to authenticated
  with check (auth.uid() = user_id);

-- Users may delete only their own score records.
drop policy if exists "Users can delete their own scores" on public.scores;
create policy "Users can delete their own scores"
  on public.scores for delete
  to authenticated
  using (auth.uid() = user_id);

create index if not exists scores_score_created_idx
  on public.scores (score desc, created_at desc);
create index if not exists scores_user_id_idx
  on public.scores (user_id);
