-- NeonPlay shared online leaderboard (run in Supabase SQL Editor)
create table if not exists public.scores (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  player_name text not null check (char_length(player_name) between 1 and 24),
  game text not null check (char_length(game) between 1 and 60),
  score integer not null check (score >= 0),
  created_at timestamptz not null default now()
);

alter table public.scores enable row level security;

drop policy if exists "Anyone can read leaderboard scores" on public.scores;
create policy "Anyone can read leaderboard scores"
  on public.scores for select
  to anon, authenticated
  using (true);

drop policy if exists "Signed-in users can submit their own scores" on public.scores;
create policy "Signed-in users can submit their own scores"
  on public.scores for insert
  to authenticated
  with check (auth.uid() = user_id);

-- Users may delete only their own score records.
drop policy if exists "Users can delete their own scores" on public.scores;
create policy "Users can delete their own scores"
  on public.scores for delete
  to authenticated
  using (auth.uid() = user_id);

create index if not exists scores_score_created_idx
  on public.scores (score desc, created_at desc);
create index if not exists scores_user_id_idx
  on public.scores (user_id);

-- NEONPLAY UPDATE 3.0: account-based player profile, favorites, collections and recent games.
-- Run this in the same Supabase project's SQL Editor. RLS keeps each profile private to its owner.
create table if not exists public.player_profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null default 'Player' check (char_length(display_name) between 1 and 24),
  xp integer not null default 0 check (xp >= 0),
  level integer not null default 1 check (level >= 1),
  favorites jsonb not null default '[]'::jsonb check (jsonb_typeof(favorites) = 'array'),
  recent_games jsonb not null default '[]'::jsonb check (jsonb_typeof(recent_games) = 'array'),
  collections jsonb not null default '[]'::jsonb check (jsonb_typeof(collections) = 'array'),
  updated_at timestamptz not null default now()
);

alter table public.player_profiles enable row level security;
drop policy if exists "Players can read their own profile" on public.player_profiles;
create policy "Players can read their own profile"
  on public.player_profiles for select to authenticated
  using (auth.uid() = user_id);
drop policy if exists "Players can create their own profile" on public.player_profiles;
create policy "Players can create their own profile"
  on public.player_profiles for insert to authenticated
  with check (auth.uid() = user_id);
drop policy if exists "Players can update their own profile" on public.player_profiles;
create policy "Players can update their own profile"
  on public.player_profiles for update to authenticated
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

-- NEONPLAY UPDATE 5.0: player game reviews. Run this file in Supabase SQL Editor.
create table if not exists public.game_reviews (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  game text not null check (char_length(game) between 2 and 60),
  rating integer not null check (rating between 1 and 5),
  comment text not null check (char_length(comment) between 10 and 800),
  player_name text not null default 'Player' check (char_length(player_name) between 1 and 24),
  created_at timestamptz not null default now()
);
alter table public.game_reviews enable row level security;
drop policy if exists "Anyone can read game reviews" on public.game_reviews;
create policy "Anyone can read game reviews" on public.game_reviews
  for select to anon, authenticated using (true);
drop policy if exists "Signed-in players can post reviews as themselves" on public.game_reviews;
create policy "Signed-in players can post reviews as themselves" on public.game_reviews
  for insert to authenticated with check (auth.uid() = user_id);
drop policy if exists "Players can update their own reviews" on public.game_reviews;
create policy "Players can update their own reviews" on public.game_reviews
  for update to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);
drop policy if exists "Players can delete their own reviews" on public.game_reviews;
create policy "Players can delete their own reviews" on public.game_reviews
  for delete to authenticated using (auth.uid() = user_id);
create index if not exists game_reviews_created_idx on public.game_reviews (created_at desc);
create index if not exists game_reviews_game_idx on public.game_reviews (game, created_at desc);
